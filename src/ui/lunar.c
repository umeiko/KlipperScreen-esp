static long days_from_civil(int y, int m, int d)
{
    y -= m <= 2 ? 1 : 0;
    long era = (y >= 0 ? y : y - 399) / 400;
    unsigned yoe = (unsigned)(y - era * 400);
    unsigned doy = (153 * (unsigned)(m + (m > 2 ? -3 : 9)) + 2) / 5 + (unsigned)d - 1;
    unsigned doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    return era * 146097 + (long)doe - 719468;
}

void solar_to_lunar(int sy, int sm, int sd, lunar_t *out)
{
    int ly = sy;
    uint32_t ny = s_new_year[ly - 1900];
    int nyy = (int)(ny / 10000), nym = (int)(ny / 100 % 100), nyd = (int)(ny % 100);
    if (days_from_civil(nyy, nym, nyd) - days_from_civil(sy, sm, sd) > 0) {
        ly--;
        ny = s_new_year[ly - 1900];
        nyy = (int)(ny / 10000); nym = (int)(ny / 100 % 100); nyd = (int)(ny % 100);
    }
    long days_passed = days_from_civil(sy, sm, sd) - days_from_civil(nyy, nym, nyd);
    uint32_t yc = s_lunar_code[ly - 1900];
    int mdays[13];
    int n = 0;
    for (int i = 5; i <= 16; i++) mdays[n++] = (yc >> (i - 1)) & 1 ? 30 : 29;
    int leap_m = (int)(yc & 0xF);
    if (leap_m) {
        for (int i = n; i > leap_m; i--) mdays[i] = mdays[i - 1];
        mdays[leap_m] = (yc >> 16) ? 30 : 29;
        n++;
    }
    long cum = 0;
    int month = 0, day = 0;
    for (int pos = 0; pos < n; pos++) {
        cum += mdays[pos];
        if (days_passed + 1 <= cum) { month = pos + 1; day = mdays[pos] - (int)(cum - days_passed) + 1; break; }
    }
    int leap_flag = 0;
    int lm;
    if (leap_m == 0 || month <= leap_m) lm = month;
    else lm = month - 1;
    if (leap_m != 0 && month == leap_m + 1) leap_flag = 1;
    out->year = ly; out->month = lm; out->day = day; out->leap = leap_flag;
}
